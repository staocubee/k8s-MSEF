#!/usr/bin/env python3
"""
Export manuscript-ready tables from measured results only.

Reads results/json/*.json and results/runs/*/ (metrics.json, latency-analysis-*.json)
and prints Markdown tables. Every value carries the run_id it came from; any
value that has not been measured is printed as PENDING. Nothing is hardcoded.

  python3 scripts/export_results_tables.py > results/manuscript-tables.md
"""
import glob, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = lambda n: (json.load(open(p)) if os.path.exists(p := os.path.join(ROOT, "results", "json", n)) else None)

def cell(v, fmt="{:.4f}", run=None):
    if v is None: return "PENDING"
    s = fmt.format(v) if isinstance(v, (int, float)) else str(v)
    return f"{s} ({run})" if run else s

def ci(c): return "PENDING" if not c or c[0] is None else f"[{c[0]}, {c[1]}]"

print("<!-- generated by scripts/export_results_tables.py; do not edit numbers by hand -->\n")
mbr, spr, pes, des, rdr, rrsr, mttd, fpr = (J(n) for n in ("mbr.json", "spr.json", "pes.json", "des.json", "rdr.json", "rrsr.json", "mttd.json", "fpr.json"))
print("## Layer 2/3 and composite scores\n\n| Metric | Value | 95% CI | n | Run |\n| --- | --- | --- | --- | --- |")
for name, d, n in (("MBR", mbr, mbr and mbr.get("evaluated")), ("SPR / IES", spr, spr and spr.get("evaluated"))):
    print(f"| {name} | {cell(d and d.get('score'))} | {ci(d and d.get('ci95_wilson'))} | {n if n is not None else 'PENDING'} | {d.get('run_id') if d else 'PENDING'} |")
for name, d in (("PES", pes), ("DES", des)):
    print(f"| {name} | {cell(d and d.get('score'))} | n/a (composite) | n/a | inputs' runs |")
print("\n## Layer 4\n\n| Metric | Value | 95% CI | n | Run |\n| --- | --- | --- | --- | --- |")
for name, d, k, n in (("RDR", rdr, "score", rdr and rdr.get("total")), ("RRSR", rrsr, "score", rrsr and rrsr.get("detected")),
                      ("OFPR", fpr, "score", fpr and fpr.get("windows"))):
    print(f"| {name} | {cell(d and d.get(k))} | {ci(d and d.get('ci95_wilson'))} | {n if n is not None else 'PENDING'} | {d.get('run_id') if d else 'PENDING'} |")
print(f"| MTTD (s) | {cell(mttd and mttd.get('mean'), '{:.3f}')} | {ci(mttd and mttd.get('ci95'))} | {mttd.get('n') if mttd else 'PENDING'} | {mttd.get('run_id') if mttd else 'PENDING'} |")
m = rrsr and rrsr.get("mttc_seconds")
print(f"| MTTC (ms) | {cell(m and m.get('mean') and m['mean']*1000, '{:.1f}')} | {ci(m and m.get('ci95') and [round(x*1000,1) if x is not None else None for x in m['ci95']])} | {m.get('n') if m else 'PENDING'} | {rrsr.get('run_id') if rrsr else 'PENDING'} |")
print("\n## Admission latency (per analysis file)\n")
files = sorted(glob.glob(os.path.join(ROOT, "results", "runs", "*", "latency-analysis-*.json")))
if not files: print("PENDING: no latency analysis has been run.")
for f in files:
    a = json.load(open(f)); b = a["baseline"]
    print(f"### {os.path.basename(f)}\n\n| Config | n | failed | Mean | SD | P50 | P90 | P95 | P99 | Welch t (df), p | Mann-Whitney p | Cohen's d | Δ median 95% CI | Run |")
    print("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for e in [b] + a["runs"]:
        v = e.get("vs_baseline", {})
        w = f"{v['welch_t']} ({v['welch_df']}), {v['welch_p']:.2e}" if v else "baseline"
        mw = f"{v['mannwhitney_p']:.2e}" if v else ""
        print(f"| {e['config']} | {e.get('n')} | {e.get('failed')} | {e.get('mean_ms')} | {e.get('sd_ms')} | {e.get('p50_ms')} | {e.get('p90_ms')} | {e.get('p95_ms')} | {e.get('p99_ms')} | {w} | {mw} | {v.get('cohens_d', '')} | {v.get('delta_median_ci95_bootstrap', '')} | {e['run']} |")
    print()
